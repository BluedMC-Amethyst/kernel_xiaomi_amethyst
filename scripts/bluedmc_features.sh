#!/usr/bin/env bash
# bluedmc_features.sh - BluedMC kernel for amethyst: one git commit per feature on top of TechAmethyst v1.2
#
# Base: TechAmethyst v1.2 = android14-6.1-2025-06_r17 (6.1.138, stock sublevel; 6.1.172/v1.3 flickers on HyperOS) + KernelSU-Next + SUSFS + BBR + NTFS3
#       + wakelock blocker + -mtune=cortex-a720.  https://github.com/TheTechGuy69/techamethyst-kernel (tag v1.2)
# BluedMC adds (each its own commit, each KMI-gated against the stock .ko files before it is kept):
#   brand    -BluedMC-<ver> version string, /sys/kernel/bluedmc/{version,features}
#   misc     tmpfs xattr + POSIX ACL
#   net      IP sets, xt_set/addrtype/recent/LOG, REJECT/MASQUERADE v6, CAKE, TTL/HL, connmark,
#            BIC/Westwood/HTCP built in (WildKernels networking set; WireGuard already =y in GKI)
#   cifs     SMB/CIFS client
#   ntsync   /dev/ntsync (Wine/Proton sync primitives)
#   bbg      Baseband Guard LSM (blocks writes to critical partitions)
#   bbrv3    TCP BBRv3 (default congestion control)
#   perf     WildKernels performance patch set
#   opt      -mtune=cortex-a710 -O3 (+ full LTO at build time), see stage_opt
#   lz4      LZ4 v1.10.0 + arm64 NEON decompressor (zram/f2fs/erofs), patches/lz4-1.10.0-arm64-neon-6.1.patch
# opt-in (not in "all"):
#   lean     drop some runtime hardening defaults for speed (init_on_alloc, kstack offset randomisation, KFENCE)
#   version  re-brand an existing BluedMC tree to $BMC_VER
#   clang18  build with AOSP clang r522817 (clang 18) and -mtune=cortex-a720 (experimental)
#   autofdo  AutoFDO: compile with a sample profile, AFDO_PROFILE=<file> (experimental, see docs/AUTOFDO.md)
#
# usage: bluedmc_features.sh <stage>...      stages run in the order given; "all" = every stage in order
# env:   TOP (Kleaf workspace, default ~/AmethystGKI/ws)  BMC_VER (default v1.0)
#        KP  (WildKernels/kernel_patches checkout)  BBG_REF (Baseband-guard commit, default pinned)
set -euo pipefail

TOP=${TOP:-$HOME/AmethystGKI/ws}
C=$TOP/common
BMC_VER=${BMC_VER:-v1.0}
BRAND=BluedMC
KP=${KP:-$TOP/../kernel_patches}
REPO=$(cd "$(dirname "$0")/.." && pwd)
KP_REPO=${KP_REPO:-https://github.com/WildKernels/kernel_patches}
BBG_REPO=${BBG_REPO:-https://github.com/vc-teahouse/Baseband-guard}
BBG_REF=${BBG_REF:-48d9fde}
DEFC=$C/arch/arm64/configs/gki_defconfig
ALL_STAGES=(brand misc net cifs ntsync bbg bbrv3 perf opt lz4)   # + opt-in: lean, version

say(){ printf '\n\033[1;36m[BluedMC] %s\033[0m\n' "$*"; }
die(){ printf '\n\033[1;31m[ERROR] %s\033[0m\n' "$*"; exit 1; }
[ -d "$C/.git" ] || die "no kernel git at $C"

setcfg(){   # setcfg CONFIG_X y|n|"value"
  local k=$1 v=$2 line
  if [ "$v" = n ]; then line="# $k is not set"; else line="$k=$v"; fi
  sed -i "/^$k=/d; /^# $k is not set/d" "$DEFC"
  echo "$line" >> "$DEFC"
}
commit(){ git -C "$C" add -A; git -C "$C" -c user.name="${GIT_AUTHOR_NAME:-BluedMC}" -c user.email="${GIT_AUTHOR_EMAIL:-bluedmc@users.noreply.github.com}" commit -qm "$1"; say "committed: $(git -C "$C" log -1 --format='%h %s')"; }
kp(){ [ -d "$KP/.git" ] || git clone -q --depth 1 "$KP_REPO" "$KP"; }
apply(){    # apply <patch> : must apply cleanly (no fuzz > default, no rejects)
  ( cd "$C" && patch -p1 --forward --no-backup-if-mismatch < "$1" ) || die "patch failed: $1"
  [ -z "$(cd "$C" && find . -name '*.rej' -print -quit)" ] || die "rejects after $1"
}


# ------------------------------------------------------------------------------------------------ brand
stage_brand(){
  say "brand: -$BRAND-$BMC_VER"
  grep -qE '^echo "\$res-TechAmethyst-v[0-9.]+"$' "$C/scripts/setlocalversion" || die "setlocalversion: TechAmethyst suffix not found"
  sed -i -E "s/^echo \"\\\$res-TechAmethyst-v[0-9.]+\"\$/echo \"\$res-$BRAND-$BMC_VER\"/" "$C/scripts/setlocalversion"
  git -C "$C" mv kernel/techamethyst.c kernel/bluedmc.c
  sed -i 's/^obj-y += techamethyst.o$/obj-y += bluedmc.o/' "$C/kernel/Makefile"
  python3 - "$C/kernel/bluedmc.c" "$BRAND $BMC_VER" <<'PY'
import sys, re
p, ver = sys.argv[1], sys.argv[2]
s = open(p).read()
s = s.replace("/* TechAmethyst status node: /sys/kernel/techamethyst/{version,features} */",
              "/* BluedMC status node: /sys/kernel/bluedmc/{version,features} (based on TechAmethyst) */")
s = re.sub(r'"TechAmethyst v[0-9.]+"', '"%s"' % ver, s)
# features string is regenerated by update_features(); keep a placeholder marker
s = re.sub(r'return sysfs_emit\(buf, "%s\\n", "ksu=[^"]*"\);', lambda m: r'return sysfs_emit(buf, "%s\n", BLUEDMC_FEATURES);', s)
s = s.replace('kobject_create_and_add("techamethyst", kernel_kobj)', 'kobject_create_and_add("bluedmc", kernel_kobj)')
s = s.replace("techamethyst_init", "bluedmc_init")
s = s.replace("#include <linux/sysfs.h>\n", '#include <linux/sysfs.h>\n\n#define BLUEDMC_FEATURES "ksu susfs bbr ntfs3 wlblock tune"\n', 1)
open(p, "w").write(s)
PY
  grep -q 'BLUEDMC_FEATURES);' "$C/kernel/bluedmc.c" || die "status node rewrite failed"
  commit "$BRAND: brand -$BRAND-$BMC_VER, /sys/kernel/bluedmc status node"
}
add_feature(){ sed -i "s/^#define BLUEDMC_FEATURES \"\(.*\)\"$/#define BLUEDMC_FEATURES \"\1 $1\"/" "$C/kernel/bluedmc.c"; }

