# ------------------------------------------------------------------------------------------------ bbg
stage_bbg(){
  say "bbg: Baseband Guard @ $BBG_REF"
  local B; B=$(mktemp -d)
  git clone -q "$BBG_REPO" "$B/bbg"; git -C "$B/bbg" checkout -q "$BBG_REF"
  local rev; rev=$(git -C "$B/bbg" rev-parse --short HEAD)
  # copy (not symlink like setup.sh) so the tree is self-contained in git and in Bazel's sandbox
  rm -rf "$C/security/baseband-guard"; mkdir -p "$C/security/baseband-guard"
  ( cd "$B/bbg" && cp -r Kconfig Makefile LICENSE *.c *.h tracing "$C/security/baseband-guard/" )
  rm -rf "$B"
  grep -q 'baseband-guard/' "$C/security/Makefile" || printf '\nobj-$(CONFIG_BBG) += baseband-guard/\n' >> "$C/security/Makefile"
  if ! grep -q 'security/baseband-guard/Kconfig' "$C/security/Kconfig"; then
    awk '{a[NR]=$0} END{last=0; for(i=1;i<=NR;i++) if(a[i] ~ /^endmenu[[:space:]]*$/) last=i;
         for(i=1;i<=NR;i++){ if(i==last) print "source \"security/baseband-guard/Kconfig\""; print a[i] }}' \
      "$C/security/Kconfig" > "$C/security/Kconfig.tmp" && mv "$C/security/Kconfig.tmp" "$C/security/Kconfig"
  fi
  grep -q "#define DEFINE_LSM(lsm)" "$C/include/linux/lsm_hooks.h" || die "no DEFINE_LSM: BBG would need SELinux struct edits"
  # add baseband_guard to the default LSM order (same edit as the WildKernels action)
  sed -i '/^config LSM$/,/^help$/{ /^[[:space:]]*default/ { /baseband_guard/! s/selinux/selinux,baseband_guard/ } }' "$C/security/Kconfig"
  grep -q 'selinux,baseband_guard' "$C/security/Kconfig" || die "LSM default not updated"
  # gki_defconfig may pin CONFIG_LSM; keep it in sync
  if grep -q '^CONFIG_LSM=' "$DEFC"; then sed -i '/^CONFIG_LSM=/{/baseband_guard/! s/selinux/selinux,baseband_guard/}' "$DEFC"; fi
  setcfg CONFIG_BBG y
  add_feature bbg
  commit "$BRAND: bbg Baseband Guard LSM ($rev)"
}

